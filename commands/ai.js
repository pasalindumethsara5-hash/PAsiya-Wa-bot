const axios = require("axios");
const config = require("../config");

module.exports = {
  ai: {
    name: "ai",
    alias: ["gpt", "ask", "gemini"],
    category: "ai",
    desc: "Ask anything to AI",
    async execute(sock, m, args) {
      const query = args.join(" ");
      if (!query) {
        return sock.sendMessage(
          m.chat,
          { text: `⚠️ *Please provide a question or topic!*\n\n*Example:* ${config.prefix}ai What is quantum computing?` },
          { quoted: m }
        );
      }

      await sock.sendMessage(m.chat, { text: "💭 *PASIYA AI is thinking...*" }, { quoted: m });

      try {
        // Free AI API endpoint
        const response = await axios.get(
          `https://text.pollinations.ai/${encodeURIComponent(query)}?system=You are PASIYA AI, a smart and friendly AI assistant created by PASIYA for WhatsApp. Be helpful, concise, and friendly.`
        );

        const reply = response.data || "Sorry, I could not generate an answer right now.";
        await sock.sendMessage(
          m.chat,
          {
            text: `🤖 *PASIYA AI Response:*\n\n${reply}\n\n> 👑 *Powered by PASIYA-MD*`,
          },
          { quoted: m }
        );
      } catch (err) {
        console.error("AI Error:", err);
        await sock.sendMessage(
          m.chat,
          { text: "❌ *Failed to connect to AI server. Please try again in a few seconds!*" },
          { quoted: m }
        );
      }
    },
  },

  imagine: {
    name: "imagine",
    alias: ["dalle", "genimage", "photo"],
    category: "ai",
    desc: "Generate AI image from text prompt",
    async execute(sock, m, args) {
      const prompt = args.join(" ");
      if (!prompt) {
        return sock.sendMessage(
          m.chat,
          { text: `⚠️ *Please provide an image prompt!*\n\n*Example:* ${config.prefix}imagine a cute cyber cat in neon city` },
          { quoted: m }
        );
      }

      await sock.sendMessage(m.chat, { text: "🎨 *Generating image, please wait a moment...*" }, { quoted: m });

      try {
        const imageUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=1024&height=1024&nologo=true`;
        
        await sock.sendMessage(
          m.chat,
          {
            image: { url: imageUrl },
            caption: `🎨 *Generated by PASIYA-MD AI*\n📝 *Prompt:* ${prompt}\n👑 *Owner:* ${config.ownerName}`,
          },
          { quoted: m }
        );
      } catch (err) {
        console.error("Image Gen Error:", err);
        await sock.sendMessage(m.chat, { text: "❌ *Failed to generate image. Please try again!*" }, { quoted: m });
      }
    },
  },
};
